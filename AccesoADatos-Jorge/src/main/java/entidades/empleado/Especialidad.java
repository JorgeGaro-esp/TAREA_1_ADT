package entidades.empleado;

public class Especialidad {

	//Atributos
	private	String nombre;

	//Constructor
	public Especialidad(String nombre) {
		super();
		this.nombre = nombre;
	}

	//Getters y Setters
	public String getNombre() {
		return nombre;
	}

	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	
	
	
	
	
}
